import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = resolve(scriptDirectory, "..");
const sourcePath = resolve(projectDirectory, "public/do-vui-do-meo.html");
const outputPath = resolve(projectDirectory, "db/seed/questions.sql");

const normalizeQuestion = (value) =>
  value.trim().replace(/\s+/g, " ").toLocaleLowerCase("vi");

const escapeSql = (value) => value.replaceAll("'", "''");

const requireNonEmptyString = (question, field, index) => {
  if (typeof question[field] !== "string" || question[field].trim() === "") {
    throw new Error(`Question ${index + 1} must have a non-empty ${field}.`);
  }
};

const validateQuestion = (question, index) => {
  if (question === null || typeof question !== "object" || Array.isArray(question)) {
    throw new Error(`Question ${index + 1} must be an object.`);
  }

  for (const field of ["topic", "age", "tag", "q", "explain"]) {
    requireNonEmptyString(question, field, index);
  }

  if (!Array.isArray(question.opts) || question.opts.length !== 4) {
    throw new Error(`Question ${index + 1} must have exactly four options.`);
  }

  question.opts.forEach((option, optionIndex) => {
    if (typeof option !== "string" || option.trim() === "") {
      throw new Error(`Question ${index + 1} option ${optionIndex + 1} must be non-empty.`);
    }
  });

  if (!Number.isInteger(question.correct) || question.correct < 0 || question.correct > 3) {
    throw new Error(`Question ${index + 1} must have a correct index from 0 to 3.`);
  }
};

const html = await readFile(sourcePath, "utf8");
const match = html.match(
  /const questions = (\[[\s\S]*?\n\]);[\s\S]*?questions\.push\(\.\.\.(\[[\s\S]*?\n\])\);/
);

if (!match) {
  throw new Error("Could not find both quiz question arrays in the fallback HTML.");
}

const initialQuestions = vm.runInNewContext(`(${match[1]})`);
const additionalQuestions = vm.runInNewContext(`(${match[2]})`);
const questions = [...initialQuestions, ...additionalQuestions];

if (questions.length !== 180) {
  throw new Error(`Expected 180 quiz questions, found ${questions.length}.`);
}

questions.forEach(validateQuestion);

const insertStatements = questions.map((question) => {
  const values = [
    question.topic,
    question.age,
    question.tag,
    question.q,
    normalizeQuestion(question.q),
    ...question.opts,
    question.explain,
  ].map((value) => `'${escapeSql(value)}'`);

  return `INSERT OR IGNORE INTO questions (topic, age, tag, question_text, normalized_question, option_a, option_b, option_c, option_d, correct_index, explanation, is_active, created_at, updated_at) VALUES (${values.slice(0, 9).join(", ")}, ${question.correct}, ${values[9]}, 1, unixepoch(), unixepoch());`;
});

const sql = [
  "-- Generated by scripts/generate-quiz-seed.mjs. Do not edit manually.",
  "BEGIN TRANSACTION;",
  ...insertStatements,
  "COMMIT;",
  "",
].join("\n");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, sql, "utf8");

console.log(`Generated ${questions.length} quiz questions at db/seed/questions.sql`);
